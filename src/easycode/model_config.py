def pricing_for_model(model_name):
    """First matching preset for a model id, or None when pricing is unknown (no estimate, no cap)."""
    name = (model_name or "").lower()
    return next((entry for entry in PRICING if entry["match"] in name), None)


def cost_of(pricing, prompt_tokens, completion_tokens, cached_tokens):
    """CNY estimate for one call; cached prompt tokens bill at the cheaper cache-hit rate."""
    cached = min(max(cached_tokens or 0, 0), prompt_tokens or 0)
    return ((prompt_tokens or 0) - cached) * pricing["prompt"] / 1e6 \
        + cached * pricing["cached"] / 1e6 \
        + (completion_tokens or 0) * pricing["completion"] / 1e6


