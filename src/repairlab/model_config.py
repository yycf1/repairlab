def read_env_config(env_path):
    """Parse the three model keys from .env without executing or echoing file contents."""
    values = {key: "" for key in ENV_KEYS}
    path = Path(env_path)
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key in values:
            values[key] = value
    return values


def write_env_config(env_path, *, model, base_url, api_key):
    """Persist the three keys into .env, preserving unrelated lines and comments."""
    path = Path(env_path)
    updates = {MODEL_KEY: model, BASE_URL_KEY: base_url, API_KEY_KEY: api_key}
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else [
        "# Generated by the RepairLab workbench model settings page.",
    ]
    written = set()
    result = []
    for line in lines:
        stripped = line.strip()
        key = stripped.partition("=")[0].strip() if "=" in stripped and not stripped.startswith("#") else None
        if key in updates:
            result.append(f"{key}={updates[key]}")
            written.add(key)
        else:
            result.append(line)
    for key in ENV_KEYS:
        if key not in written:
            result.append(f"{key}={updates[key]}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(result).rstrip("\n") + "\n", encoding="utf-8")
    for key, value in updates.items():
        os.environ[key] = value
    return updates


def apply_to_process(values):
    """Make saved values effective immediately without a service restart."""
    for key, value in values.items():
        os.environ[key] = value


def mask_key(key):
    if not key:
        return ""
    return "***" + key[-4:] if len(key) >= 8 else "已设置"


def public_model_settings(settings):
    values = read_env_config(settings.env_path)
    stored_key = values[API_KEY_KEY] or settings.api_key
    base_url = values[BASE_URL_KEY] or settings.base_url
    provider = next((p["id"] for p in PROVIDERS if p["base_url"] and p["base_url"].rstrip("/") == base_url), "custom")
    return {"configured": settings.model_ready, "model": values[MODEL_KEY] or settings.model,
            "base_url": base_url, "api_key_masked": mask_key(stored_key), "provider": provider}


def _profiles_path(settings):
    return settings.data_dir / "model-profiles.json"


def load_profiles(settings):
    """Saved model profiles: {"active": id, "items": [{id, label, base_url, model, api_key}]}.

    Seeded from the live .env configuration on first use so a fresh install shows
    its current model instead of an empty list.
    """
    path = _profiles_path(settings)
    data = None
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            data = None
    if isinstance(data, dict) and isinstance(data.get("items"), list):
        items = [p for p in data["items"] if isinstance(p, dict) and p.get("id") and p.get("model")]
        active = data.get("active")
        if active not in {p["id"] for p in items}:
            active = items[0]["id"] if items else None
        return {"active": active, "items": items}
    values = read_env_config(settings.env_path)
    if values[MODEL_KEY] and values[BASE_URL_KEY]:
        payload = {"active": "default", "items": [
            {"id": "default", "label": values[MODEL_KEY], "base_url": values[BASE_URL_KEY],
             "model": values[MODEL_KEY], "api_key": values[API_KEY_KEY] or settings.api_key}]}
        save_profiles(settings, payload)
        return payload
    return {"active": None, "items": []}


def save_profiles(settings, payload):
    path = _profiles_path(settings)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def public_profiles(settings):
    """Picker payload; keys are masked and never returned in full."""
    payload = load_profiles(settings)
    current = public_model_settings(settings)
    items = [{**{k: p[k] for k in ("id", "base_url", "model")},
              "label": p.get("label") or p["model"], "api_key_masked": mask_key(p.get("api_key", "")),
              "active": p["id"] == payload["active"]} for p in payload["items"]]
    return {"active": payload["active"], "items": items, "configured": current["configured"]}


def upsert_profile(settings, *, base_url, model, api_key):
    """Add or update a profile matching (base_url, model); returns its id."""
    payload = load_profiles(settings)
    base_url = base_url.rstrip("/")
    profile = next((p for p in payload["items"]
                    if p["base_url"].rstrip("/") == base_url and p["model"] == model), None)
    if profile is None:
        profile = {"id": "m-" + uuid.uuid4().hex[:8], "base_url": base_url, "model": model}
        payload["items"].append(profile)
    profile["label"] = model
    if api_key:
        profile["api_key"] = api_key
    payload["active"] = profile["id"]
    save_profiles(settings, payload)
    return profile["id"]


def activate_profile(settings, profile_id):
    """Switch the active configuration to a saved profile (updates .env + process)."""
    payload = load_profiles(settings)
    profile = next((p for p in payload["items"] if p["id"] == profile_id), None)
    if profile is None:
        raise ValueError("该模型配置不存在，请刷新后重试。")
    values = write_env_config(settings.env_path, model=profile["model"], base_url=profile["base_url"],
                              api_key=profile.get("api_key", ""))
    apply_to_process(values)
    payload["active"] = profile["id"]
    save_profiles(settings, payload)
    return public_model_settings(settings)


def test_connection(base_url, api_key, model, *, client=None, timeout=12):
    """One minimal chat completion against the operator-provided endpoint.

    Errors are reported by HTTP status only; provider bodies are never persisted or echoed.
    """
    url = base_url.strip().rstrip("/") + "/chat/completions"
    owned = client is None
    client = client or httpx.Client(timeout=httpx.Timeout(timeout, connect=5))
    started = time.monotonic()
    try:
        response = client.post(url, headers={"Authorization": "Bearer " + api_key},
            json={"model": model, "messages": [{"role": "user", "content": "连接测试，请只回复：ok"}],
                  "temperature": 0, "max_tokens": 512})
    except httpx.HTTPError:
        return {"ok": False, "message": "无法连接接口；请检查网络、地址与代理设置。", "latency_ms": None}
    finally:
        if owned:
            client.close()
    latency = round((time.monotonic() - started) * 1000)
    if response.status_code == 200:
        body = response.json()
        message = (body.get("choices") or [{}])[0].get("message", {})
        # Thinking models may spend the whole completion budget on reasoning_content.
        if message.get("content"):
            return {"ok": True, "message": f"连接成功，模型 {model} 已响应。", "latency_ms": latency}
        if message.get("reasoning_content"):
            return {"ok": True, "message": f"连接成功，模型 {model} 已响应（思考型输出）。", "latency_ms": latency}
        return {"ok": False, "message": "接口可达，但响应缺少 choices/message 内容；请确认是 Chat Completions 接口。",
                "latency_ms": latency}
    reasons = {401: "密钥无效或未授权（HTTP 401）。", 403: "密钥无权访问该模型（HTTP 403）。",
               404: "接口地址或模型名不存在（HTTP 404）。", 429: "触发限流（HTTP 429）；连接本身有效，可稍后重试。"}
    return {"ok": False, "message": reasons.get(response.status_code,
            f"接口返回 HTTP {response.status_code}；未保存响应正文。"), "latency_ms": latency}
